export function evaReply(text, ctx = {}) {
  const t = (text || '').toLowerCase().trim();
  const all = ctx.allLessons || LESSONS;

  /* ответы, которые смотрят в состояние приложения */
  if (has(t, 'сегодня', 'что делать', 'программ', 'план', 'задани')) {
    const day = ctx.today ?? 0;
    const d = ctx.program?.days?.[day];
    const items = d ? [d.affirmation, d.practice, d.masterclass].map((id) => all.find((l) => l.id === id)).filter(Boolean) : [];
    return {
      text: d
        ? `Сегодня день ${day + 1} твоей программы. Три шага — три звезды:\n\n${items
            .map((l, i) => `${i + 1}. ${TYPE_META[l.type].short} · ${l.title} (${l.min} мин)`)
            .join('\n')}\n\nНачни с аффирмации — это займёт минуту.`
        : 'Программа появится сразу после короткого теста — шесть вопросов, две минуты.',
      lessons: items,
    };
  }

  if (has(t, 'балл', 'звезд', 'очк', 'уровен', 'сколько у меня', 'прогресс')) {
    return {
      text: `У тебя ${ctx.points ?? 0} баллов и ${ctx.stars ?? 0} из 21 звезды на этой неделе.\n\nЗа каждую практику — звезда, за полностью закрытую неделю — суперзвезда и +200 баллов. Баллы превращаются в бонусные рубли в маркете.`,
      lessons: [],
    };
  }

  if (has(t, 'почему', 'как подобрал', 'откуда', 'алгоритм')) {
    return {
      text: `Я прочитала твои ответы, превратила их в теги и сравнила с тегами у ${
        ctx.scanned || all.length
      } единиц контента. Чем больше совпадений — тем выше урок в подборке.\n\nСейчас в твоём профиле сильнее всего: ${(ctx.topTags || []).slice(0, 4).join(', ') || 'спокойствие, энергия'}. Именно поэтому программа выглядит так.`,
      lessons: [],
    };
  }

  if (has(t, 'купить', 'товар', 'маркет', 'коврик', 'подушк', 'свеч')) {
    return {
      text: 'В маркете есть всё для практики: коврики, подушки для медитации, свечи, чай и одежда. Часть суммы можно оплатить бонусными баллами.',
      lessons: [],
      go: '#/market',
      goLabel: 'Открыть маркет',
    };
  }

  if (has(t, 'курс', 'обучен', 'эксперт')) {
    return {
      text: 'У экспертов есть платные курсы — это продолжение бесплатных практик, которые тебе уже понравились. Загляни в раздел «Курсы».',
      lessons: [],
      go: '#/courses',
      goLabel: 'Смотреть курсы',
    };
  }

  if (has(t, 'сообществ', 'групп', 'общат', 'подруг', 'чат')) {
    return {
      text: 'В сообществе есть группы по интересам: мамочки, йога, медитация, работа и деньги, беременность, женское здоровье. Можно задать вопрос — часто отвечают сами эксперты.',
      lessons: [],
      go: '#/community',
      goLabel: 'Перейти в сообщество',
    };
  }

  for (const it of INTENTS) {
    if (it.test(t)) {
      return { text: it.reply(ctx), lessons: it.tags.length ? pick(it.tags, 3, all) : [] };
    }
  }

  /* если ничего не подошло — ищем по словам */
  const found = searchLessons(t, all, 3);
  if (found.length) {
    return { text: 'Вот что у нас есть по твоему запросу:', lessons: found };
  }

  return {
    text: 'Я пока не совсем поняла 🤍 Скажи проще — например: «мне тревожно», «нет сил», «плохо сплю», «что мне делать сегодня».',
    lessons: [],
  };
}

export function evaGreeting(ctx = {}) {
  const h = new Date().getHours();
  const part = h < 5 ? 'Доброй ночи' : h < 12 ? 'Доброе утро' : h < 18 ? 'Добрый день' : 'Добрый вечер';
  return `${part}${ctx.name ? ', ' + ctx.name : ''} 🤍\n\nЯ Ева. Могу подобрать практику под настроение, объяснить твою программу или просто побыть рядом. Расскажи, как ты?`;
}

