/* подбираем разные форматы: практику, мастер-класс и аффирмацию */
const pick = (arr, n = 3, all = LESSONS) => {
  const score = (l) => (l.tags || []).filter((t) => arr.includes(t)).length;
  const found = all.filter((l) => score(l) > 0).sort((a, b) => score(b) - score(a));
  const out = [];
  for (const type of ['practice', 'masterclass', 'affirmation']) {
    const l = found.find((x) => x.type === type && !out.includes(x));
    if (l) out.push(l);
  }
  for (const l of found) {
    if (out.length >= n) break;
    if (!out.includes(l)) out.push(l);
  }
  return out.slice(0, n);
};

