/* ---------- память ---------- */
function AM(){
  const m = S.adamMem;
  if(!m || typeof m !== 'object' || Array.isArray(m)) S.adamMem = {seen:[], insp:[], at:0, n:0};
  if(!S.adamMem.seen) S.adamMem.seen = [];
  if(!S.adamMem.insp) S.adamMem.insp = [];
  return S.adamMem;
}

/* ---------- о ней самой ----------
   Лучший комплимент — из её же данных: он не может быть рассылкой. */
function adamPersonal(){
  const out = [];
  const n = S.name ? S.name : '';
  const st = typeof streak === 'function' ? streak() : 0;
  if(st >= 2) out.push(`${plural(st, 'день', 'дня', 'дней')} подряд закрыты полностью. Знаешь, что это значит? Что на тебя можно положиться — и в первую очередь тебе самой.`);
  const sw = typeof starsWeek === 'function' ? starsWeek() : 0;
  if(sw >= 6) out.push(`${sw} звёзд за неделю — и ни одной за «просто зашла». Каждая — это дело, которое ты довела. Я такое замечаю.`);
  const all = S.starsAll || 0;
  if(all >= 15) out.push(`У тебя ${plural(all, 'звезда', 'звезды', 'звёзд')} за всё время. Это не про приложение — это про то, сколько раз ты выбрала себя, когда могла не выбирать.`);
  const taste = S.taste || {};
  const fav = Object.keys(taste).sort((a, b) => taste[b] - taste[a])[0];
  if(fav && taste[fav] >= 2) out.push(`Ты раз за разом доделываешь материалы про ${fav}. Не бросаешь на половине. Так поступают те, кто решил всерьёз.`);
  if((S.likes || []).length >= 3) out.push(`Ты ставишь звёзды тому, что откликнулось, — значит, слушаешь себя, а не «надо». Это и есть вкус.`);
  if((S.joined || []).length >= 2) out.push(`Ты в ${plural((S.joined || []).length, 'группе', 'группах', 'группах')} сразу. Люди тянутся туда, где живёт тепло, — и часто его туда приносят. Это про тебя.`);
  if(!out.length) return null;
  const t = out[Math.floor(Math.random() * out.length)];
  return n ? `${n}, ${t.charAt(0).toLowerCase() + t.slice(1)}` : t;
}

/* новый комплимент: сначала о ней, потом из списка без повторов */
function adamPick(kind){
  const m = AM();
  if(kind !== 'insp' && Math.random() < 0.4){
    const own = adamPersonal();
    if(own) return own;
  }
  const pool = kind === 'insp' ? ADAM_INSPIRE : ADAM_LINES;
  const seen = kind === 'insp' ? m.insp : m.seen;
  let free = pool.map((t, i) => i).filter(i => seen.indexOf(i) < 0);
  if(!free.length){ seen.length = 0; free = pool.map((t, i) => i); }
  const i = free[Math.floor(Math.random() * free.length)];
  seen.push(i);
  const t = pool[i];
  return (S.name && kind !== 'insp' && Math.random() < 0.5) ? `${S.name}, ${t.charAt(0).toLowerCase()}${t.slice(1)}` : t;
}

/* ---------- переписка ---------- */
function adamThread(){
  if(typeof initInbox === 'function') initInbox();
  return chanThread('adam');
}
function adamSay(text, act){
  const t = adamThread();
  const d = new Date();
  t.msgs.push({me:false, t:text, act:act || '',
    tm:String(d.getHours()).padStart(2, '0') + ':' + String(d.getMinutes()).padStart(2, '0')});
  if(t.msgs.length > 40) t.msgs = t.msgs.slice(-40);
  t.unread = true; t.ago = 'только что';
  S.inbox = [t].concat(S.inbox.filter(x => x !== t));
  schedulePersist();
  return t;
}

/* Сам пишет раз в день: не раньше девяти утра и только когда приложение
   открыто. Первое письмо — знакомство, дальше — комплимент дня. */
let ADAM_HOUR = 9;                 // let, а не const: в тесте час подменяют
function adamWake(){
  if(S.screen !== 'app' || !S.user || (S.role && S.role !== 'user')) return false;
  const m = AM(), now = new Date();
  if(now.getHours() < ADAM_HOUR) return false;
  const today = now.toDateString();
  if(m.day === today) return false;
  m.day = today; m.n = (m.n || 0) + 1;
  if(m.n === 1){
    adamSay((S.name ? S.name + ', привет. ' : 'Привет. ') +
      'Я Адам. Ева ведёт твою программу, а я здесь ради другого: раз в день говорить тебе что-то хорошее — про тебя, а не про дела. ' +
      'Начну сегодня.\n\n' + adamPick(), 'adamMore');
  } else {
    adamSay(adamPick(), 'adamMore');
  }
  return true;
}

/* по кнопке — прямо сейчас */
function adamAsk(kind){
  const t = adamSay(adamPick(kind), 'adamMore');
  t.unread = false;                                  // она сама попросила — это прочитано
  if(S.page === 'inbox') S.inboxTab = 'adam';
  render();
  toast(kind === 'insp' ? 'От Адама' : 'Комплимент от Адама');
}

/* ответ, когда ему пишут: благодарность, грусть, всё остальное */
function adamReply(text){
  const ws = evaWords(text), ns = ' ' + ws.join(' ') + ' ';
  const has = arr => arr.some(p => p.indexOf(' ') >= 0 ? ns.indexOf(p) >= 0 : evaHas(ws, [p]));
  let t;
  if(has(['спасиб', 'благодар', 'приятн']))
    t = ['Не за что. Это просто правда — я её только произнёс.',
         'Пожалуйста. Приходи за этим, когда захочешь: у меня не кончается.',
         'Обращайся. И запомни это на завтра — завтра тоже пригодится.'][Math.floor(Math.random() * 3)];
  else if(has(['плох', 'грустн', 'устал', 'тяжел', 'слез', 'плач', 'одинок', 'не могу']))
    t = 'Слышу. Не буду говорить «всё будет хорошо» — скажу другое: ' + adamPick('insp') +
        '\n\nЕсли захочешь не слов, а дела, — Ева подберёт что-то на пять минут. Но это потом. Сейчас просто побудь.';
  else if(has(['привет', 'здравств', 'добр', 'хай']))
    t = (S.name ? 'Привет, ' + S.name + '. ' : 'Привет. ') + adamPick();
  else if(has(['кто ты', 'ты кто', 'ты робот', 'ты настоящ']))
    t = 'Я Адам — напарник Евы. Не человек и не притворяюсь: я знаю, что ты делаешь на платформе, и умею об этом сказать по-хорошему. Больше ничего не умею — и не собираюсь.';
  else if(has(['неправд', 'не верю', 'врешь', 'льстишь', 'подхалим']))
    t = 'Понимаю недоверие. Тогда без красивых слов, только факт: ' + (adamPersonal() || 'ты здесь и читаешь это — уже больше, чем делает большинство в такой день.');
  else
    t = adamPick(Math.random() < 0.5 ? 'insp' : '');
  adamSay(t, 'adamMore');
  return t;
}

/* открыть вкладку «Комплимент» из любого места */
function openAdam(){
  resetViews(); S.page = 'inbox'; S.thread = null; S.inboxTab = 'adam';
  render(); window.scrollTo(0, 0);
}

