/* Сколько слов фразы совпало с названием — по началам слов, чтобы «нидру»
   нашло «Йога-нидра», а «стыда» — «Деньги без стыда». */
const EVA_STOP = ['себя', 'тебя', 'меня', 'себе', 'тебе', 'мне', 'как', 'что', 'для', 'про', 'перед', 'после',
  'без', 'при', 'или', 'это', 'эти', 'все', 'всех', 'есть', 'быть', 'хочу', 'надо', 'можно', 'нужно', 'мой', 'моя',
  'мое', 'свой', 'своя', 'свое', 'свои', 'твой', 'твоя', 'твое', 'день', 'дня', 'дней', 'сегодня', 'очень', 'просто',
  'опять', 'снова', 'постоянно', 'всегда', 'никогда', 'который', 'которая', 'чтобы', 'когда', 'если', 'может'];
function evaTitleHits(ws, title){
  const tw = evaLow(title).replace(/[^a-zа-я0-9]+/g, ' ').trim().split(' ')
    .filter(w => w.length > 2 && EVA_STOP.indexOf(w) < 0);
  /* четыре первые буквы: русское слово меняет хвост, а не начало;
     служебные слова («себя», «как») названием не считаются */
  return ws.filter(w => w.length > 3 && EVA_STOP.indexOf(w) < 0 && tw.some(t => t.slice(0, 4) === w.slice(0, 4))).length;
}
function evaFindLesson(ws){
  const rank = LIB.filter(x => x.status === 'live').map(x => ({x, n: evaTitleHits(ws, x.title)}))
    .filter(r => r.n).sort((a, b) => b.n - a.n);
  const best = rank[0];
  if(!best) return null;
  /* одно совпавшее слово — только если оно длинное и редкое: «нидра», «заземлен» */
  if(best.n === 1 && !ws.some(w => w.length >= 5 && evaLow(best.x.title).indexOf(w.slice(0, 4)) >= 0 && !/^(практ|расск|мастер|аффир|медит|котор)/.test(w))) return null;
  return best.x;
}
