function evaUpcoming(n){
  const today = new Date(); today.setHours(0, 0, 0, 0);
  const live = EVENTS.filter(e => e.status === 'live');
  const soon = live.filter(e => { const d = evDay(e.d); return d && d >= today; })
    .sort((a, b) => evDay(a.d) - evDay(b.d));
  const mine = S.tags || [];
  const fit = e => { const ex = EXPERTS.find(x => x.n === e.by); return ex && ex.t.some(t => mine.indexOf(t) >= 0) ? 1 : 0; };
  const pool = soon.length ? soon : live.slice().sort((a, b) => evDay(b.d) - evDay(a.d));
  return {past: !soon.length, list: pool.slice().sort((a, b) => fit(b) - fit(a)).slice(0, n || 3)};
}
