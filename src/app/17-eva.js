/* ---------- микрофон ----------
   Распознавание тоже браузерное и бесплатное. Оно работает не везде, и
   это нормально: кнопка просто говорит, в чём дело, а печатать можно
   всегда. Второе нажатие выключает — иначе на телефоне непонятно, как
   остановить слушание. */
let EVA_REC = null;
const EVA_MIC_ERR = {
  'not-allowed':'Микрофон запрещён в настройках браузера',
  'service-not-allowed':'Микрофон запрещён в настройках браузера',
  'no-speech':'Я ничего не услышала',
  'audio-capture':'Микрофон не найден',
  'network':'Распознаванию речи нужен интернет'
};
function listen(){
  const SR = window.SpeechRecognition || window.webkitSpeechRecognition;
  if(!SR) return toast('Голосовой ввод работает в Chrome и Safari — напиши текстом');
  if(EVA_REC){ try { EVA_REC.stop(); } catch(e){} return; }
  speechStop();
  const r = new SR();
  r.lang = 'ru-RU'; r.interimResults = true; r.maxAlternatives = 1;
  EVA_REC = r; S.evaMic = true; render();
  r.onresult = e => {
    let fin = '', tmp = '';
    for(let i = e.resultIndex; i < e.results.length; i++){
      const t = e.results[i][0].transcript;
      if(e.results[i].isFinal) fin += t; else tmp += t;
    }
    if(tmp){                                  // показываем, что слышно, прямо в поле
      S.evaDraft = tmp;
      const f = $('#vin'); if(f) f.value = tmp;
    }
    if(fin.trim()){ S.evaDraft = ''; ask(fin); }
  };
  r.onerror = e => toast(EVA_MIC_ERR[e.error] || 'Не расслышала, попробуй ещё раз');
  r.onend = () => { EVA_REC = null; S.evaMic = false; render(); };
  try { r.start(); } catch(e){ EVA_REC = null; S.evaMic = false; toast('Микрофон занят'); }
}

