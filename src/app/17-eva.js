/* ---------- разбор фразы ----------
   По-настоящему русский текст мы не разбираем: достаточно сравнивать
   начала слов. «устала», «уставшая», «устаю», «усталость» начинаются на
   «уста» — одна основа в таблице ловит весь куст, а заодно и опечатки в
   хвосте слова, которых в живой переписке большинство. */
function evaWords(s){
  return String(s == null ? '' : s).toLowerCase().replace(/ё/g, 'е')
    .replace(/[^a-zа-я0-9]+/g, ' ').trim().split(' ').filter(Boolean);
}
const evaHas = (ws, stems) => stems.some(st => ws.some(w => w.indexOf(st) === 0));
/* «не помогает», «не хочу» — отрицание переворачивает смысл, поэтому
   его надо видеть отдельно от самого слова */
const evaNot = (ws, stems) => ws.some((w, i) =>
  i > 0 && /^(не|ни|нет)$/.test(ws[i-1]) && stems.some(st => w.indexOf(st) === 0));

/* ---------- что посоветовать ----------
   Совет — это не «займись собой», а конкретный материал: с автором,
   длиной и кнопками. Берём лучший по той же оценке, которой собирается
   программа, и не предлагаем одно и то же дважды за разговор. */
function evaFind(tags, types, maxMin){
  const p = profileOf();
  const said = EM().said;
  const fit = LIB.filter(x => x.status === 'live' && allowed(x, p)
    && (!types || types.indexOf(x.type) >= 0)
    && (!maxMin || x.min <= maxMin)
    && x.tags.some(t => tags.indexOf(t) >= 0));
  if(!fit.length) return null;
  /* Чем свежее совет, тем сильнее штраф: самый последний уходит в самый
     низ, а давний возвращается, когда перебрали остальное. Без этого на
     узкой теме Ева второй раз подряд советует то же самое. */
  const rank = fit.map(x => ({x, s: scoreItem(x, p).score
    + x.tags.filter(t => tags.indexOf(t) >= 0).length * 7
    - (said.indexOf(x.id) >= 0 ? 200 - said.indexOf(x.id) * 12 : 0)}));
  rank.sort((a, b) => b.s - a.s);
  const best = rank[0].x;
  EM().said = [best.id].concat(said.filter(id => id !== best.id)).slice(0, 14);
  return best;
}

const EVA_KIND = {affirm:'Аффирмация', practice:'Практика', class:'Мастер-класс'};
const evaMin = n => plural(n, 'минута', 'минуты', 'минут');
/* Название в кавычках, но если оно само с кавычками — «Я имею право на
   «нет»» — вторые не ставим: читается как опечатка. */
const evaItem = x => `${EVA_KIND[x.type]} ${x.title.indexOf('«') >= 0 ? x.title : '«' + x.title + '»'} — ${x.expert}, ${evaMin(x.min)}.`;

/* Кнопки под ответом. «В план» не показываем, если материал уже в дне:
   лишняя кнопка, которая ничего не делает, злит больше, чем её отсутствие. */
function evaActs(x){
  const acts = [['Открыть', `openLesson('${attJs(x.id)}')`]];
  const day = (S.program || [])[S.day];
  if(day && !(day.tasks || []).some(t => t.id === x.id))
    acts.push(['В план на сегодня', `evaAdd('${attJs(x.id)}')`]);
  return acts;
}
/* ответ с советом: текст + карточка + кнопки */
function evaWith(text, tags, types, maxMin){
  const x = evaFind(tags, types, maxMin);
  if(!x) return {t:text};
  return {t:text + '\n\n' + evaItem(x), a:evaActs(x)};
}

function evaAdd(id){
  const x = LIB.find(i => i.id === id);
  const day = (S.program || [])[S.day];
  if(!x || !day) return;
  if((day.tasks || []).some(t => t.id === id)) return toast('Уже в плане на сегодня');
  day.tasks.push(task(x, S.slot));
  tasteAdd(x.tags, 0.5);                      // сама попросила — это её тема
  toast('Добавила в план');
  evaPush({r:'eva', t:`Добавила «${x.title}» в сегодняшний день. Отметишь, когда сделаешь.`});
  schedulePersist(); render();
}

