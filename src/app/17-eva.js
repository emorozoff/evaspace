/* ---------- память разговора ----------
   Всё служебное держим в одном поле: так его проще сохранять и невозможно
   забыть половину при переносе в другой аккаунт. */
function EM(){
  const m = S.evaMem;
  if(!m || typeof m !== 'object' || Array.isArray(m))
    S.evaMem = {asked:{}, seen:[], said:[], turn:0, unread:0, n:0, at:0, seenAt:0};
  if(!S.evaMem.asked) S.evaMem.asked = {};
  if(!S.evaMem.seen) S.evaMem.seen = [];
  if(!S.evaMem.said) S.evaMem.said = [];
  return S.evaMem;
}

/* ---------- выбор смысла ----------
   Считаем совпадения по всем строкам таблицы и берём самую уверенную.
   Основа из двух слов весит больше одного слова: «нет сил» — точнее, чем
   «сил». Короткие слова («да», «нет», «еще») сравниваем целиком, иначе
   «дай» превратится в «да», а «нету» — в согласие. */
function evaScore(item, ws, ns){
  let n = 0;
  item.k.forEach(st => {
    if(st.indexOf(' ') >= 0){                  // основа из двух слов — самая точная примета
      if(ns.indexOf(st) >= 0) n += 2.5;
      return;
    }
    /* Короткое слово сравниваем целиком, иначе «дай» станет «да», а
       «нету» — согласием. Если короткая основа нужна именно как начало
       слова, в таблице она помечена звёздочкой: «цен*» ловит и цену, и
       ценность, но не центр. */
    const star = st.charAt(st.length - 1) === '*';
    const base = star ? st.slice(0, -1) : st;
    const hit = (!star && base.length <= 3) ? ws.indexOf(base) >= 0 : evaHas(ws, [base]);
    if(hit) n += base.length >= 7 ? 1.3 : 1;
  });
  return n;
}

function evaThink(q){
  const ws = evaWords(q);
  if(!ws.length) return 'Напиши словами — я разберусь.';
  const ns = ' ' + ws.join(' ') + ' ';
  /* название курса, практики, встречи или имя эксперта — точнее любой темы */
  const ent = evaEntity(ws);
  if(ent){ EM().topic = null; return ent; }
  let rank = EVA_I.map(i => ({i, s:evaScore(i, ws, ns)}))
    .filter(x => x.s >= 1).sort((a, b) => b.s - a.s);
  /* «курс про сон», «практика от тревоги»: слово-контейнер говорит, ЧТО
     она ищет, тема — про что. Контейнер важнее, тему подхватит сам ответ. */
  const box = [['курс', 'courses'], ['практик', 'practice'], ['мастер', 'practice'], ['эксперт', 'experts'], ['мероприят', 'events'], ['встреч', 'events']]
    .find(b => evaHas(ws, [b[0]]) && rank.some(x => x.i.id === b[1]));
  if(box && rank[0].s < 2.5) rank = rank.filter(x => x.i.id === box[1]).concat(rank.filter(x => x.i.id !== box[1]));
  /* «да» и «нет» — короткий ответ на предложение Евы. В длинной фразе
     («не умею говорить нет») они значат совсем другое, поэтому там мы их
     не слушаем и берём следующий по точности смысл. */
  const pick = rank.find(x => !(ws.length > 3 && (x.i.id === 'yes' || x.i.id === 'no'))) || rank[0];
  if(pick){
    let use = pick.i;
    const flip = EVA_FLIP[use.id];
    if(flip && evaNot(ws, flip.k)) use = EVA_I.find(x => x.id === flip.to) || use;
    const prev = EM().topic;              // «ещё» продолжает прошлую тему, а не само себя
    EM().topic = use.id;
    return use.f(ws, q, prev);
  }
  /* Ничего не совпало — но, может, она назвала тему библиотеки своим
     словом: «заземление», «благодарность». Ищем по тегам и заголовкам. */
  const tag = allTags().map(t => t[0]).find(t => evaHas(ws, [t.slice(0, Math.max(4, t.length - 2))]));
  if(tag){
    EM().topic = null;
    return evaWith(`По теме «${tag}» у меня есть материалы — вот самый подходящий тебе.`, [tag]);
  }
  const hit = LIB.filter(x => x.status === 'live')
    .find(x => ws.some(w => w.length > 4 && x.title.toLowerCase().replace(/ё/g, 'е').indexOf(w) >= 0));
  if(hit) return {t:`Похоже, ты про это: ${evaItem(hit)}`, a:evaActs(hit)};
  /* Совсем не поняла — честно говорю и предлагаю путь, а не тупик. */
  EM().topic = null;
  return {t:'Я не поняла — скажи по-другому или выбери, о чём речь.',
    a:[['Про сегодняшний день', "ask('что мне сегодня делать')"],
       ['Про состояние', "ask('мне тяжело')"],
       ['Про платформу', "ask('что ты умеешь')"]]};
}

