/* ---------- как Ева задаёт вопрос ---------- */
const EVA_ASK_GAP = 6 * 24 * 3600e3;          // один и тот же вопрос — не чаще раза в неделю
function evaNextAsk(){
  const m = EM(), now = Date.now();
  const free = EVA_ASKS.filter(q => {
    if(m.asked[q.id] && now - m.asked[q.id] < EVA_ASK_GAP) return false;
    try { return q.when ? !!q.when() : true; } catch(e){ return false; }
  });
  if(!free.length) return null;
  return free[(m.turn || 0) % free.length].id;
}

function evaAskNow(id){
  const q = EVA_ASKS.find(x => x.id === id);
  if(!q) return;
  const m = EM();
  m.ask = id; m.asked[id] = Date.now(); m.n = 0;
  evaReply({t:q.t, q:true, a:q.o.map((o, i) => [o.l, `evaPickOpt(${i})`])});
}

/* клик по варианту ответа */
function evaPickOpt(i){
  const m = EM(), q = EVA_ASKS.find(x => x.id === m.ask);
  if(!q || !q.o[i]) return toast('Этот вопрос уже закрыт');
  const o = q.o[i];
  m.ask = null;
  evaPush({r:'me', t:o.l});
  render(); evaScroll();
  evaReply(o.f());
  schedulePersist();
}

function evaSkipAsk(){
  const m = EM();
  if(!m.ask) return;
  m.ask = null; m.n = 0;
  evaReply('Хорошо, не буду настаивать. Спрошу в другой раз.');
  schedulePersist(); render();
}

/* ответ на вопрос Евы своими словами */
function evaTryOpt(id, text){
  const q = EVA_ASKS.find(x => x.id === id);
  if(!q) return null;
  const ws = evaWords(text), ns = ' ' + ws.join(' ') + ' ';
  if(q.free){
    EM().why = String(text).slice(0, 300);          // остаётся у Евы, профиль не трогаем
    const tag = allTags().map(t => t[0]).find(t => evaHas(ws, [t.slice(0, Math.max(4, t.length - 2))]));
    if(tag){ tasteAdd([tag], 0.8); return evaWith(`Спасибо, записала. По твоим словам вижу тему «${tag}» — начну с неё.`, [tag]); }
    return 'Спасибо, записала. Буду держать это в голове, когда собираю неделю.';
  }
  let best = null, top = 0;
  q.o.forEach(o => {
    const s = evaScore({k:o.k}, ws, ns);
    if(s > top){ top = s; best = o; }
  });
  return best && top >= 1 ? best.f() : null;
}

