/* какие группы у пользовательницы — из ответов теста */
function myAudience(){
  const a = [], ans = S.answers || {}, ex = S.extra || {};
  const stage = (ans.stage || {}).t || '';
  if(stage.includes('Беременность')) a.push('pregnant');
  if(stage.includes('малыша')){
    a.push(ex.baby === 'до 6 мес' ? 'newborn' : ex.baby === '6-18 мес' ? 'newborn' : 'toddler');
    if(ex.baby === '1,5-3 года') a.push('toddler');
  }
  if(stage.includes('школьника')) a.push('school');
  if(stage.includes('взрослые'))  a.push('grown');
  if(stage.includes('Карьера') || stage.includes('направление')) a.push('career', 'nokids');
  const rel = (ans.rel || {}).t || '';
  if(rel.includes('Свободна')) a.push('single');
  if(rel.includes('Замужем') || rel.includes('партнёр')) a.push('couple');
  if(rel.includes('разводе') || rel.includes('кризис')) a.push('crisis');
  const cy = typeof cycleNow === 'function' ? cycleNow() : null;
  if(cy && cy.phase.k === 'menstrual') a.push('period');
  return a;
}

