/** Всё о регионе одним объектом: справка, сообщество и цифры клуба. */
export function regionGuide(key) {
  const r = REGIONS[key];
  const g = GUIDE[key];
  const stats = regionStats(key);
  const events = EVENTS.filter((e) => e.region === key).length;
  return { key, ...r, ...g, stats, events, local: localOf(key) };
}

export const GUIDE_KEYS = REGION_KEYS.filter((k) => GUIDE[k]);
