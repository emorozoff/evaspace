export function Rules() {
  const s = useStore();
  const tier = s.profile?.tier || 'guest';
  const rank = RANK[tier];
  return (
    <div className="aska-rules">
      <div className="hint">Правила АСЬКИ. Чем выше твой уровень, тем больше открыто 🔓</div>
      {SECTIONS.map((sec) => {
        const open = rank >= RANK[sec.need];
        return (
          <div key={sec.title} className={`groupbox aska-rule${open ? '' : ' locked'}`}>
            <div className="legend">{open ? '' : '🔒 '}{sec.title}</div>
            {open ? <ul>{sec.body.map((b) => <li key={b}>{b}</li>)}</ul> : <div className="hint">{sec.teaser}</div>}
          </div>
        );
      })}
    </div>
  );
}
