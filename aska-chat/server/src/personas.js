// Ответ про вечеринку без «мозга»: был ли, оценка 1–10, отзыв
export function parseParty(text) {
  const raw = String(text || '').trim();
  const t = raw.toLowerCase().replace(/ё/g, 'е');
  const words = t.split(/[^a-zа-я0-9]+/).filter(Boolean);
  let rating = 0;
  const of10 = t.match(/(?:^|\D)(10|[1-9])(?:[.,]\d)?\s*(?:\/|из)\s*(?:10|десяти)(?!\d)/);
  if (of10) rating = Number(of10[1]);
  else if (words.length <= 8) {
    const w = words.find((x) => /^(10|[1-9])$/.test(x) || NUM_WORDS[x]);
    if (w) rating = Number(w) || NUM_WORDS[w];
  }
  // \b в JS не видит границ русских слов — границы проверяем сами
  const no = /(не был|не ходил|не пошл|не смог|не получилось|не попал|меня там не|^(нет|неа|не)(?![а-я]))/.test(t);
  if (no && !rating) return { attended: 'no', rating: 0, comment: '' };
  const yes = rating > 0 || /(^(да|ага|угу|конечно|канеш[а-я]*|yes)(?![а-я])|(?<![а-я])был|ходил|пришл|тусил|зажигал|отрывал)/.test(t);
  if (!yes) return { attended: 'unknown', rating: 0, comment: '' };
  const rest = words.filter((w) => !PARTY_FILLER.has(w) && !NUM_WORDS[w] && !/^\d+$/.test(w));
  const comment = rest.some((w) => w.length >= 3) ? raw.slice(0, 300) : '';
  return { attended: 'yes', rating, comment };
}
