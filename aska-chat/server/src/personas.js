// Чем Батя занят по часам (по Москве)
export function batyaStatus(hour, weekday) {
  if (hour < 6 || hour >= 23) return { emoji: '😴', text: 'сплю' };
  if (hour < 8) return { emoji: '☕', text: 'пью чай' };
  if (hour < 12) return weekday === 0 || weekday === 6 ? { emoji: '🥒', text: 'на даче' } : { emoji: '🔧', text: 'в гараже' };
  if (hour < 14) return { emoji: '🍲', text: 'обедаю' };
  if (hour < 18) return weekday === 6 ? { emoji: '🎣', text: 'на рыбалке' } : { emoji: '🛠', text: 'чиню кран' };
  if (hour < 21) return { emoji: '📺', text: 'смотрю новости' };
  return { emoji: '⚽', text: 'смотрю футбол' };
}

