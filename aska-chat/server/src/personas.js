export function batyaScripted(text, nextQuestion) {
  const t = String(text || '').toLowerCase().replace(/ё/g, 'е').trim();
  // Человеку плохо — отвечаем целиком и с вопросами не лезем
  if (BATYA_RE[0][0].test(t)) return BATYA_RE[0][1];
  for (const [re, out] of BATYA_RE) if (re.test(t)) return Math.random() < 0.3 && nextQuestion && out.length === 1 ? [...out, nextQuestion] : out;
  const plain = BATYA_PLAIN[Math.floor(Math.random() * BATYA_PLAIN.length)];
  return nextQuestion && Math.random() < 0.6 ? [plain, nextQuestion] : [plain];
}

