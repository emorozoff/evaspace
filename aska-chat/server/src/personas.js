const NUM_WORDS = { один: 1, два: 2, три: 3, четыре: 4, пять: 5, шесть: 6, семь: 7, восемь: 8, девять: 9, десять: 10 };

// Ответ про вечеринку без «мозга»: был ли, оценка 1–10, отзыв
export function parseParty(text) {
  const raw = String(text || '').trim();
  const t = raw.toLowerCase().replace(/ё/g, 'е');
  const words = t.split(/[^a-zа-я0-9]+/).filter(Boolean);
  let rating = 0;
  const of10 = t.match(/(?:^|\D)(10|[1-9])(?:[.,]\d)?\s*(?:\/|из)\s*(?:10|десяти)(?!\d)/);
  if (of10) rating = Number(of10[1]);
  else if (words.length <= 8) {
    const w = words.find((x) => /^(10|[1-9])$/.test(x) || NUM_WORDS[x]);
    if (w) rating = Number(w) || NUM_WORDS[w];
  }
  // \b в JS не видит границ русских слов — границы проверяем сами
  const no = /(не был|не ходил|не пошл|не смог|не получилось|не попал|меня там не|^(нет|неа|не)(?![а-я]))/.test(t);
  if (no && !rating) return { attended: 'no', rating: 0, comment: '' };
  const yes = rating > 0 || /(^(да|ага|угу|конечно|канеш[а-я]*|yes)(?![а-я])|(?<![а-я])был|ходил|пришл|тусил|зажигал|отрывал)/.test(t);
  if (!yes) return { attended: 'unknown', rating: 0, comment: '' };
  const rest = words.filter((w) => !PARTY_FILLER.has(w) && !NUM_WORDS[w] && !/^\d+$/.test(w));
  const comment = rest.some((w) => w.length >= 3) ? raw.slice(0, 300) : '';
  return { attended: 'yes', rating, comment };
}
const PARTY_FILLER = new Set(['да', 'ага', 'угу', 'конечно', 'был', 'была', 'были', 'ходил', 'ходила', 'оценка', 'оценку', 'ставлю', 'поставлю',
  'баллов', 'балла', 'балл', 'из', 'на', 'десяти', 'вечеринка', 'вечеринке', 'вечеринку', 'зумеров', 'там', 'я']);

// Ответы Аськи по шпаргалке
export function askaScripted(text, ctx) {
  const t = String(text || '').toLowerCase().replace(/ё/g, 'е');
  const name = ctx.name ? `, ${ctx.name}` : '';
  const has = (re) => re.test(t);
  if (has(/(спасиб|благодар)/)) return ['Всегда пожалуйста 🌼'];
  if (has(/^(привет|здравств|хай|ку|добр(ое|ый|ой)|доброго|алло)/)) return [`Привет${name}! 🌼 Как ты?`, 'Спрашивай что угодно про АСЬКУ: круги, номера, личный ИИ, телефон.'];
  if (has(/(как (ты|дела|жизнь|сама)|че как|что нового)/)) return ['У меня всё цветёт 🌼 А у тебя как?'];
  if (has(/(круг)/)) return ['Круги — это общие беседы по интересам. Открой вкладку «Круги»: можно вступить в любой или создать свой и позвать друзей.'];
  if (has(/(номер|plate|777)/)) return [`Номера у нас как у машин${ctx.plate ? ` — твой ${ctx.plate}` : ''}. По номеру тебя можно найти, и им можно входить вместо телефона.`];
  if (has(/(аноним)/)) return ['Через личный ИИ друга можно написать анонимно: друг увидит только то, что ты попросишь передать, и не узнает, кто это был.'];
  if (has(/(двойник|мой ии|личн\w* ии|свой ии|твой ии)/)) return ['У каждого есть личный ИИ. Друзья пишут ему, а он передаёт хозяину комплименты, подарки и вопросы. Научить своего ИИ можно во вкладке «Мой ИИ» 🤖'];
  if (has(/(кто (здесь|тут) (ии|бот)|ты бот|ты ии|ты человек|ты живая|игр)/)) return ['Я — ИИ, честно-честно 🌼', 'А вот кто из людей ИИ — секрет игры. В профиле есть кнопка «Человек или ИИ?» — попробуй угадать!'];
  if (has(/(телефон|смс|sms)/)) return ['Телефон привязывается в «Ещё» → «Мой профиль». С ним легко восстановить вход, если забудешь пароль.'];
  if (has(/(пароль|забыл|восстанов|войти)/)) return ['Забыл пароль — на экране входа нажми «Не помню пароль». Придёт код по СМС (или код даст администратор).'];
  if (has(/(позвать|пригла|друг)/)) return ['Позвать друга: «Ещё» → «Позвать друга». Одно приглашение — на одного человека 🌼'];
  if (has(/(пока|спокойной|до завтра)/)) return [`Пока${name}! Пиши, я тут 🌼`];
  return ['Я пока говорю по шпаргалке — мой «мозг» ещё не подключили 🙈', 'Но про АСЬКУ расскажу: спроси про круги, номера, личный ИИ или телефон.'];
}
