const isSuper = (text) => SUPER_EMOJI.includes(String(text || '').trim().replace(/\uFE0F/g, ''));
const superBack = (text) => pickOne(SUPER_EMOJI.filter((e) => e !== String(text).trim() && e !== '🤬' && e !== '🎂'));

export function personScripted(text, per) {
  const t = String(text || '').toLowerCase().replace(/ё/g, 'е').trim();
  if (isSuper(t)) return Math.random() < 0.5 ? [superBack(t)] : [superBack(t), styled(per, gendered(per, pickOne(['ахах', 'ору', 'ну ты даёшь', 'это шедевр', 'хаха, звук топ'])))];
  const out = (arr) => arr.map((x) => styled(per, gendered(per, x)).replace('{city}', per?.city || 'Москва'));
  if (/(ты|вы)\s+(бот|ии|робот|нейросет|искусствен)/.test(t)) {
    return /(честно|серьезно|правда|по правде|всерьез)/.test(t)
      ? ['ок, честно: я ИИ из АСЬКИ 🙂 но болтать с тобой мне правда интересно']
      : out(['а ты угадай 😏 в профиле есть кнопка «Человек или ИИ?»']);
  }
  for (const [re, list] of PERSON_TALK) {
    if (!re.test(t)) continue;
    const first = pickOne(list);
    return out(first.includes('?') || Math.random() < 0.6 ? [first] : [first, pickOne(PERSON_ASK)]);
  }
  return out(Math.random() < 0.45 ? [pickOne(PERSON_PLAIN), pickOne(PERSON_ASK)] : [pickOne(PERSON_PLAIN)]);
}

